function attrs(
  partial: Record<string, string>,
  extra?: {
    styleNumber?: string;
    availability?: string;
    productionNote?: string;
    measurements?: string;
    content?: string;
    components?: string;
    setIncludes?: string;
  },
): Record<string, string> {
  return {
    "Style Number": extra?.styleNumber ?? "",
    Availability: extra?.availability ?? "Ready to ship",
    "Production note": extra?.productionNote ?? "",
    Measurements: extra?.measurements ?? "",
    Content: extra?.content ?? "",
    "No. of Components": extra?.components ?? "",
    "Wash Care": partial["Wash Care"] ?? partial.Care ?? care,
    "Country of Origin": "India",
    Manufacturer: manufacturer,
    "Set Includes": extra?.setIncludes ?? "",
    ...partial,
    Care: partial.Care ?? care,
  };
}

